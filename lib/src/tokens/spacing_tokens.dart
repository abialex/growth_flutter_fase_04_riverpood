/// Spacing scale on a 4dp base unit. Use for padding, margin and gaps
/// between elements — never a magic number outside this scale.
class AppSpacing {
  const AppSpacing._();

  /// 4dp
  static const double xs = 4;

  /// 8dp
  static const double sm = 8;

  /// 16dp
  static const double md = 16;

  /// 24dp
  static const double lg = 24;

  /// 32dp
  static const double xl = 32;

  /// 48dp
  static const double xxl = 48;
}
